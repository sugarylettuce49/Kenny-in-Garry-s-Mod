"""Kenny's Wwise .wem files -> GMod sounds + a Lua table of lines with loudness envelopes (for the jaw).

python build_audio.py <wem dir (vo/ and sfx/)> <vgmstream-cli.exe> <addon dir>
"""
import re
import subprocess
import sys
import tempfile
import wave
from collections import defaultdict
from pathlib import Path

import numpy as np

WEM, VGM, ADDON = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
ENV_HZ = 20  # envelope samples per second, one char each ('0'..'9')

# GMod-side situation -> High on Life VO events
VO = {
    "equip": ["G_Kenny_Equipped", "Global_Kenny_SwapGeneric"],
    "kill": ["G_Kenny_Kill_EnemyGeneric", "Global_Kenny_KillsEnemy"],
    "multikill": ["G_Kenny_Multikill"],
    "headshot": ["G_Kenny_Headshot"],
    "hurt": ["G_Kenny_Take_Damage", "Global_Kenny_TakesLightDamage"],
    "hurt_heavy": ["G_Kenny_Take_HeavyDamage"],
    "hurt_fire": ["G_Kenny_Hazard_DamageAcidFire"],
    "hurt_shock": ["G_Kenny_Hazard_DamageElectric"],
    "hurt_other": ["G_Kenny_Hazard_DamageGeneric"],
    "fall": ["G_Kenny_Fall_OffCliff"],
    "death": ["G_Kenny_Player_Dies"],
    "idle": ["G_Kenny_Idles_Act1", "G_Kenny_Idles_Act2"],
    "combat_idle": ["G_Kenny_Combat_Idle"],
    "first_shot": ["Global_Kenny_FirstShotBattleCries"],
    "spot": ["G_Kenny_Spot_AnyEnemies"],
    "taunt": ["VS_Kenny_GenericTaunts", "Global_Kenny_GenericEnemyTaunt"],
    "glob_ready": ["G_Kenny_Support_FireReady"],
    "glob_kill": ["G_Kenny_Support_FireKill"],
    "env_kill": ["G_Kenny_Environment_Kill"],
    "stagger": ["G_Kenny_Enemy_Staggered"],
    "refuse": ["G_Kenny_Shoot_NPC_Refusal"],
    "health": ["G_Kenny_Pickup_Health"],
    "sprint": ["G_Kenny_Sprint_ForLongTime"],
    "no_ammo": ["Global_Kenny_OutOfAmmo"],
}
SFX = {
    "fire": "Play_Weapon_Kenny_FirePrimary",
    "impact": "Play_SFX_Kenny_Fire_Basic_Impact",
    "glob_fire": "Play_Weapon_Kenny_Support_Fire",
    "glob_impact": "Play_Weapon_Kenny_Support_Impact",
    "draw": "Play_Weapon_Kenny_Draw",
    "holster": "Play_Weapon_Kenny_Holster",
    "reload": "Play_Weapon_Kenny_Reload",
}


def decode(wem, tmp):
    wav = Path(tmp) / (wem.stem + ".wav")
    subprocess.run([VGM, "-o", str(wav), str(wem)], check=True, capture_output=True)
    return wav


def envelope(wav):
    with wave.open(str(wav)) as w:
        rate, ch = w.getframerate(), w.getnchannels()
        a = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768
    a = a.reshape(-1, ch).mean(axis=1)
    hop = rate // ENV_HZ
    rms = np.array([np.sqrt(np.mean(a[i:i + hop] ** 2)) for i in range(0, len(a), hop)])
    rms = rms / (rms.max() or 1)
    return len(a) / rate, "".join(str(min(9, int(v * 10))) for v in rms)


def encode(wav, out, mp3):
    out.parent.mkdir(parents=True, exist_ok=True)
    args = ["-c:a", "libmp3lame", "-q:a", "4"] if mp3 else ["-c:a", "pcm_s16le"]
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-ar", "44100", "-ac", "1", *args, str(out)],
                   check=True)


def event_of(stem):  # Play_G_Kenny_Take_Damage_012[_Improv][_0] -> G_Kenny_Take_Damage
    s = re.sub(r"^Play_(\d+_)?", "", stem)
    s = re.sub(r"(_Improv)?(_\d+)*(_v\d+)?(_\d+)?$", "", s)
    return s.replace("_Improv", "")


lua = ["-- generated by tools/build_audio.py: Kenny's lines, {path, seconds, loudness envelope @ %d Hz}" % ENV_HZ,
       "KENNY_VO = {"]
with tempfile.TemporaryDirectory() as tmp:
    by_event = defaultdict(list)
    for wem in sorted((WEM / "vo").glob("*.wem")):
        by_event[event_of(wem.stem)].append(wem)
    for cat, events in VO.items():
        lua.append(f"\t{cat} = {{")
        n = 0
        for ev in events:
            for wem in by_event.get(ev, []):
                n += 1
                wav = decode(wem, tmp)
                dur, env = envelope(wav)
                rel = f"kenny/vo/{cat}_{n:02d}.mp3"
                encode(wav, ADDON / "sound" / rel, mp3=True)
                lua.append(f'\t\t{{"{rel}", {dur:.2f}, "{env}"}},')
        lua.append("\t},")
        print(cat, n)
    lua.append("}")

    lua.append("KENNY_SFX = {")
    for key, prefix in SFX.items():
        files = sorted((WEM / "sfx").glob(prefix + "*.wem"))
        files = [f for f in files if re.fullmatch(re.escape(prefix) + r"(_\d+)?", f.stem)]
        paths = []
        for i, wem in enumerate(files, 1):
            rel = f"kenny/sfx/{key}_{i:02d}.wav"
            encode(decode(wem, tmp), ADDON / "sound" / rel, mp3=False)
            paths.append(f'"{rel}"')
        lua.append(f"\t{key} = {{{', '.join(paths)}}},")
        print(key, len(paths))
    lua.append("}")

out = ADDON / "lua" / "kenny_hol" / "sh_vo_data.lua"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lua) + "\n")
print("wrote", out)
